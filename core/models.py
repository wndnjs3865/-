class QuantScore(BaseModel):
    """Quantitative scoring from QR agent (8 dimensions)."""
    signal_id: str
    symbol: str
    # 8 scoring dimensions (0-100 each)
    trend_alignment: float = Field(ge=0.0, le=100.0)
    momentum_score: float = Field(ge=0.0, le=100.0)
    volume_profile: float = Field(ge=0.0, le=100.0)
    volatility_regime: float = Field(ge=0.0, le=100.0)
    orderflow_imbalance: float = Field(ge=0.0, le=100.0)
    correlation_filter: float = Field(ge=0.0, le=100.0)
    statistical_edge: float = Field(ge=0.0, le=100.0)
    timing_score: float = Field(ge=0.0, le=100.0)
    # Aggregated
    total_score: float = Field(ge=0.0, le=100.0)
    grade: str  # A+, A, B+, B, C, D, F
    reasons: list[str] = Field(default_factory=list)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    def compute_total(self) -> float:
        weights = {
            "trend_alignment": 0.20,
            "momentum_score": 0.15,
            "volume_profile": 0.10,
            "volatility_regime": 0.10,
            "orderflow_imbalance": 0.15,
            "correlation_filter": 0.10,
            "statistical_edge": 0.10,
            "timing_score": 0.10,
        }
        total = sum(
            getattr(self, dim) * w for dim, w in weights.items()
        )
        self.total_score = round(total, 2)
        return self.total_score

    def compute_grade(self) -> str:
        s = self.total_score
        if s >= 90: self.grade = "A+"
        elif s >= 80: self.grade = "A"
        elif s >= 70: self.grade = "B+"
        elif s >= 60: self.grade = "B"
        elif s >= 50: self.grade = "C"
        elif s >= 40: self.grade = "D"
        else: self.grade = "F"
        return self.grade


