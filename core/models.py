class RiskValidation(BaseModel):
    """Single risk check result."""
    check_name: str
    passed: bool
    value: float | None = None
    threshold: float | None = None
    detail: str = ""


class RiskAssessment(BaseModel):
    """Full risk assessment from CRCO."""
    signal_id: str
    symbol: str
    approved: bool
    validations: list[RiskValidation] = Field(default_factory=list)
    veto_reasons: list[str] = Field(default_factory=list)
    risk_score: float = Field(ge=0.0, le=100.0, default=0.0)
    max_position_size: float = 0.0
    recommended_leverage: float = 1.0
    circuit_breaker_active: bool = False
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @property
    def vetoed(self) -> bool:
        return not self.approved


